"""Timesheet business logic — Replicon read workflows + single time-entry writes."""

from __future__ import annotations

import logging
import uuid
from datetime import date
from typing import Any

from app.clients.exceptions import (
    RepliconInvalidResponseError,
    TimeEntryValidationError,
)
from app.clients.replicon_client import RepliconClient
from app.models.timesheet_models import (
    RepliconDate,
    TimeEntryCreateResponse,
    TimesheetIdentity,
    TimesheetInspectResponse,
    TimesheetSubmitResponse,
)

logger = logging.getLogger(__name__)

TIMESHEET_SERVICE = "TimesheetService1"
TIME_ENTRY_REVISION_GROUP_SERVICE = "TimeEntryRevisionGroupService1"
TIMESHEET_GET_OPTION_CREATE_IF_NECESSARY = (
    "urn:replicon:timesheet-get-option:create-timesheet-if-necessary"
)

# Verified allocation-type URNs from a working PutTimeEntryRevisionGroup payload.
TIME_ALLOCATION_TYPE_ATTENDANCE = "urn:replicon:time-allocation-type:attendance"
TIME_ALLOCATION_TYPE_PROJECT = "urn:replicon:time-allocation-type:project"

# Verified metadata key URNs from a working PutTimeEntryRevisionGroup payload.
METADATA_KEY_IS_BILLABLE = "urn:replicon:time-entry-metadata-key:is-billable"
METADATA_KEY_TASK = "urn:replicon:time-entry-metadata-key:task"

# Schema notes exposed to operators (not guesses presented as facts).
# Best-effort status labels that mean "do not submit again" / do not overwrite entries.
# Matched as whole normalized tokens (alphanumeric only), not substrings —
# e.g. "Not Submitted" must NOT match "submitted".
_ALREADY_SUBMITTED_STATUS_TOKENS = frozenset(
    {
        "waiting",
        "waitingforapproval",
        "submitted",
        "pendingapproval",
        "approved",
        "submitting",
    }
)

PUT_SCHEMA_NOTES = [
    "Write API is TimeEntryRevisionGroupService1/PutTimeEntryRevisionGroup "
    "(not PutStandardTimesheet2).",
    "OpenAPI: for new entries, timeEntryRevisionGroup.target must be null.",
    "OpenAPI: for updates, timeEntryRevisionGroup.target.uri is the existing "
    "revision-group URI.",
    "When the timesheet is not submitted, fill overwrites an existing "
    "user/date/task entry (target.uri set). When submitted/waiting/approved, "
    "existing entries are left alone (status=existing_entry).",
    "OpenAPI: unitOfWorkId is required — generated by this service as a unique "
    "idempotency key.",
    "parameterCorrelationId is omitted on create because target is null "
    "(correlation IDs apply to TimeEntryRevisionGroupTargetParameter1).",
    "widget-ui-metadata-key:row-number is intentionally omitted — it appears in "
    "UI captures but is not confirmed as required by OpenAPI.",
    "is-billable is set to false to match the verified tenant example; make this "
    "configurable if billable time is required later.",
]

SUBMIT_SCHEMA_NOTES = [
    "Weekly submit uses TimesheetApprovalService1/Submit2 on na5 "
    "(not a TimesheetService1 operation).",
    "na5 OpenAPI required fields: timesheetUri, unitOfWorkId.",
    "comments and changeReason are optional.",
    "Submit2 submits the entire weekly timesheet period, not individual days.",
    "Approve / Reject / ForceApprove / Reopen are intentionally not implemented.",
]


class TimesheetService:
    """Encapsulates Replicon timesheet read workflows and single time-entry creates.

    Bulk weekly writes, SubmitTimesheet, CompleteTimesheet, and ApproveTimesheet
    are intentionally not implemented.
    """

    def __init__(self, client: RepliconClient) -> None:
        self._client = client

    @staticmethod
    def build_get_timesheet_for_date_payload(
        user_uri: str,
        target_date: date,
        *,
        create_if_necessary: bool = True,
    ) -> dict[str, Any]:
        """Build the verified GetTimesheetForDate2 request body."""
        payload: dict[str, Any] = {
            "userUri": user_uri,
            "date": RepliconDate.from_date(target_date).model_dump(),
        }
        if create_if_necessary:
            payload["timesheetGetOptionUri"] = TIMESHEET_GET_OPTION_CREATE_IF_NECESSARY
        return payload

    def get_timesheet(
        self,
        user_uri: str,
        target_date: date,
    ) -> dict[str, Any]:
        """Call GetTimesheetForDate2 and return the unwrapped ``d`` payload."""
        payload = self.build_get_timesheet_for_date_payload(user_uri, target_date)
        logger.info(
            "get_timesheet",
            extra={"user_uri": user_uri, "date": target_date.isoformat()},
        )
        response = self._client.post(
            TIMESHEET_SERVICE,
            "GetTimesheetForDate2",
            payload,
        )
        return self._client.unwrap_d(response, operation="GetTimesheetForDate2")

    def extract_timesheet_identity(self, get_timesheet_data: dict[str, Any]) -> TimesheetIdentity:
        """Extract timesheet identity from GetTimesheetForDate2 ``d`` payload."""
        if not isinstance(get_timesheet_data, dict):
            raise RepliconInvalidResponseError(
                "GetTimesheetForDate2 payload is not an object",
                operation="GetTimesheetForDate2",
                response_body=get_timesheet_data,
            )

        timesheet = get_timesheet_data.get("timesheet")
        if not isinstance(timesheet, dict):
            raise RepliconInvalidResponseError(
                "GetTimesheetForDate2 response is missing timesheet object",
                operation="GetTimesheetForDate2",
                response_body=get_timesheet_data,
            )

        uri = timesheet.get("uri")
        if not isinstance(uri, str) or not uri.strip():
            raise RepliconInvalidResponseError(
                "GetTimesheetForDate2 response is missing timesheet.uri",
                operation="GetTimesheetForDate2",
                response_body=get_timesheet_data,
            )

        return TimesheetIdentity(
            uri=uri,
            display_text=timesheet.get("displayText"),
            slug=timesheet.get("slug"),
            format=get_timesheet_data.get("timesheetFormat"),
        )

    def get_summary(self, timesheet_uri: str) -> dict[str, Any]:
        """Call GetTimesheetSummary and return the full response (with ``d``)."""
        logger.info("get_summary", extra={"timesheet_uri": timesheet_uri})
        return self._client.post(
            TIMESHEET_SERVICE,
            "GetTimesheetSummary",
            {"timesheetUri": timesheet_uri},
        )

    def get_details(self, timesheet_uri: str) -> dict[str, Any]:
        """Call BulkGetTimesheetDetails for metadata (not task hour allocations)."""
        logger.info("get_details", extra={"timesheet_uri": timesheet_uri})
        return self._client.post(
            TIMESHEET_SERVICE,
            "BulkGetTimesheetDetails",
            {"timesheetUris": [timesheet_uri]},
        )

    def get_project_task_details(self, timesheet_uri: str) -> dict[str, Any]:
        """Call GetProjectTaskDetailsForTimesheet for available tasks/projects."""
        logger.info(
            "get_project_task_details",
            extra={"timesheet_uri": timesheet_uri},
        )
        return self._client.post(
            TIMESHEET_SERVICE,
            "GetProjectTaskDetailsForTimesheet",
            {"timesheetUri": timesheet_uri},
        )

    def inspect(self, user_uri: str, target_date: date) -> TimesheetInspectResponse:
        """Read-only workflow: resolve timesheet then fetch summary, details, tasks."""
        logger.info(
            "inspect_start",
            extra={"user_uri": user_uri, "date": target_date.isoformat()},
        )

        get_data = self.get_timesheet(user_uri, target_date)
        identity = self.extract_timesheet_identity(get_data)

        summary_raw = self.get_summary(identity.uri)
        details_raw = self.get_details(identity.uri)
        tasks_raw = self.get_project_task_details(identity.uri)

        warnings = self._build_warnings(
            identity=identity,
            details_raw=details_raw,
            tasks_raw=tasks_raw,
            target_date=target_date,
        )

        logger.info(
            "inspect_complete",
            extra={
                "timesheet_uri": identity.uri,
                "warning_count": len(warnings),
            },
        )

        return TimesheetInspectResponse(
            timesheet=identity,
            summary={"raw": summary_raw},
            details={"raw": details_raw},
            tasks={"raw": tasks_raw},
            warnings=warnings,
        )

    def create_time_entry(
        self,
        *,
        user_uri: str,
        task_name: str,
        entry_date: date,
        hours: float,
        timesheet_uri: str | None = None,
    ) -> TimeEntryCreateResponse:
        """Create or overwrite a single time-entry revision group.

        Flow:
        1. Validate hours
        2. Resolve timesheet from user_uri + date (timesheet_uri optional)
        3. Read-before-write checks (period / optional URI match)
        4. Resolve task_name → task URI via GetProjectTaskDetailsForTimesheet
        5. Check existing entries via GetTimeEntryRevisionGroupsForUserAndDateRange
        6. If duplicate and timesheet is still open → overwrite (target.uri set)
        7. If duplicate and timesheet is submitted/waiting/approved → skip
        8. Otherwise create with target=null
        """
        if hours <= 0:
            raise TimeEntryValidationError("hours must be greater than 0")

        warnings: list[str] = []
        logger.info(
            "create_time_entry_start",
            extra={
                "user_uri": user_uri,
                "timesheet_uri": timesheet_uri,
                "task_name": task_name,
                "date": entry_date.isoformat(),
                "hours": hours,
            },
        )

        resolved_timesheet_uri = self._validate_timesheet_for_write(
            user_uri=user_uri,
            timesheet_uri=timesheet_uri,
            entry_date=entry_date,
            warnings=warnings,
        )

        tasks_raw = self.get_project_task_details(resolved_timesheet_uri)
        task_uri = self.resolve_task_uri(tasks_raw, task_name)
        logger.info(
            "task_resolved",
            extra={"task_name": task_name, "task_uri": task_uri},
        )

        existing_groups = self.get_time_entry_revision_groups_for_date(
            user_uri=user_uri,
            entry_date=entry_date,
        )
        duplicate = self.find_existing_entry_for_task(
            existing_groups,
            entry_date=entry_date,
            task_uri=task_uri,
        )

        target_uri: str | None = None
        if duplicate is not None:
            existing_uri = (
                duplicate.get("uri") if isinstance(duplicate.get("uri"), str) else None
            )
            summary_raw = self.get_summary(resolved_timesheet_uri)
            timesheet_status = self._extract_summary_status(summary_raw)

            if timesheet_status and self._looks_already_submitted(timesheet_status):
                logger.warning(
                    "duplicate_time_entry_blocked",
                    extra={
                        "user_uri": user_uri,
                        "date": entry_date.isoformat(),
                        "task_uri": task_uri,
                        "existing_uri": existing_uri,
                        "timesheet_status": timesheet_status,
                    },
                )
                return TimeEntryCreateResponse(
                    status="existing_entry",
                    message=(
                        "A time entry already exists and the timesheet is not open "
                        f"for overwrite (status={timesheet_status})."
                    ),
                    user_uri=user_uri,
                    timesheet_uri=resolved_timesheet_uri,
                    task_name=task_name,
                    task_uri=task_uri,
                    entry_date=entry_date,
                    hours=hours,
                    time_entry_revision_group_uri=existing_uri,
                    existing_entry={"raw": duplicate},
                    warnings=warnings,
                    schema_notes=list(PUT_SCHEMA_NOTES),
                )

            if not existing_uri:
                raise TimeEntryValidationError(
                    "Found an existing time entry without a revision-group URI",
                    details={"entry": duplicate},
                )

            target_uri = existing_uri
            warnings.append(
                "Timesheet is not submitted; overwriting existing entry "
                f"via target.uri={existing_uri}."
            )
            logger.info(
                "overwrite_existing_time_entry",
                extra={
                    "user_uri": user_uri,
                    "date": entry_date.isoformat(),
                    "task_uri": task_uri,
                    "target_uri": target_uri,
                    "timesheet_status": timesheet_status,
                },
            )

        unit_of_work_id = self._generate_unit_of_work_id()
        payload = self.build_put_time_entry_revision_group_payload(
            user_uri=user_uri,
            task_uri=task_uri,
            entry_date=entry_date,
            hours=hours,
            unit_of_work_id=unit_of_work_id,
            target_uri=target_uri,
        )

        logger.info(
            "put_time_entry_revision_group",
            extra={
                "user_uri": user_uri,
                "task_uri": task_uri,
                "date": entry_date.isoformat(),
                "hours": hours,
                "unit_of_work_id": unit_of_work_id,
                "operation": "PutTimeEntryRevisionGroup",
                "overwrite": target_uri is not None,
                "target_uri": target_uri,
            },
        )
        put_response = self._client.put_time_entry_revision_group(payload)
        put_result = self._client.unwrap_d(
            put_response,
            operation="PutTimeEntryRevisionGroup",
        )
        result_uri = target_uri
        if isinstance(put_result, dict):
            uri_value = put_result.get("uri")
            if isinstance(uri_value, str):
                result_uri = uri_value

        logger.info(
            "create_time_entry_complete",
            extra={
                "time_entry_revision_group_uri": result_uri,
                "unit_of_work_id": unit_of_work_id,
                "overwrite": target_uri is not None,
            },
        )

        if target_uri is not None:
            return TimeEntryCreateResponse(
                status="updated",
                message=(
                    "Existing time-entry revision group overwritten "
                    "(timesheet was not submitted)."
                ),
                user_uri=user_uri,
                timesheet_uri=resolved_timesheet_uri,
                task_name=task_name,
                task_uri=task_uri,
                entry_date=entry_date,
                hours=hours,
                time_entry_revision_group_uri=result_uri,
                unit_of_work_id=unit_of_work_id,
                existing_entry={"raw": duplicate},
                replicon={"raw": put_response},
                warnings=warnings,
                schema_notes=list(PUT_SCHEMA_NOTES),
            )

        return TimeEntryCreateResponse(
            status="created",
            message="Time entry revision group created successfully.",
            user_uri=user_uri,
            timesheet_uri=resolved_timesheet_uri,
            task_name=task_name,
            task_uri=task_uri,
            entry_date=entry_date,
            hours=hours,
            time_entry_revision_group_uri=result_uri,
            unit_of_work_id=unit_of_work_id,
            replicon={"raw": put_response},
            warnings=warnings,
            schema_notes=list(PUT_SCHEMA_NOTES),
        )

    def submit_timesheet(
        self,
        *,
        user_uri: str,
        target_date: date,
        timesheet_uri: str | None = None,
        comments: str | None = None,
        change_reason: str | None = None,
    ) -> TimesheetSubmitResponse:
        """Submit the entire weekly timesheet for approval (once per period).

        Flow:
        1. Resolve timesheet from user_uri + date
        2. Read GetTimesheetSummary (before)
        3. If already submitted/approved → return already_submitted (no write)
        4. Call TimesheetApprovalService1/Submit2
        5. Re-read GetTimesheetSummary (after) for verification
        """
        warnings: list[str] = []
        logger.info(
            "submit_timesheet_start",
            extra={
                "user_uri": user_uri,
                "date": target_date.isoformat(),
                "timesheet_uri": timesheet_uri,
            },
        )

        get_data = self.get_timesheet(user_uri, target_date)
        identity = self.extract_timesheet_identity(get_data)
        resolved_uri = identity.uri

        if timesheet_uri and timesheet_uri != resolved_uri:
            raise TimeEntryValidationError(
                "timesheet_uri does not match the timesheet resolved for user/date",
                details={
                    "provided_timesheet_uri": timesheet_uri,
                    "resolved_timesheet_uri": resolved_uri,
                    "user_uri": user_uri,
                    "date": target_date.isoformat(),
                },
            )

        summary_before = self.get_summary(resolved_uri)
        before_status = self._extract_summary_status(summary_before)

        if before_status and self._looks_already_submitted(before_status):
            logger.warning(
                "submit_skipped_already_submitted",
                extra={
                    "timesheet_uri": resolved_uri,
                    "before_status": before_status,
                },
            )
            return TimesheetSubmitResponse(
                status="already_submitted",
                message=(
                    "Timesheet appears already submitted or approved; "
                    "Submit2 was not called."
                ),
                user_uri=user_uri,
                timesheet_uri=resolved_uri,
                timesheet_display_text=identity.display_text,
                date=target_date,
                before_status=before_status,
                after_status=before_status,
                summary_before={"raw": summary_before},
                summary_after={"raw": summary_before},
                warnings=warnings,
                schema_notes=list(SUBMIT_SCHEMA_NOTES),
            )

        unit_of_work_id = self._generate_unit_of_work_id()
        payload = self.build_submit2_payload(
            timesheet_uri=resolved_uri,
            unit_of_work_id=unit_of_work_id,
            comments=comments,
            change_reason=change_reason,
        )

        logger.info(
            "submit2",
            extra={
                "timesheet_uri": resolved_uri,
                "unit_of_work_id": unit_of_work_id,
                "operation": "Submit2",
            },
        )
        submit_response = self._client.submit_timesheet(payload)
        # OpenAPI: void response — "d" may be null
        if "d" not in submit_response:
            raise RepliconInvalidResponseError(
                "Submit2 response is missing the expected 'd' key",
                operation="Submit2",
                response_body=submit_response,
            )

        summary_after = self.get_summary(resolved_uri)
        after_status = self._extract_summary_status(summary_after)
        if after_status and before_status and after_status == before_status:
            warnings.append(
                "Timesheet status text did not change after Submit2; "
                f"before={before_status!r}, after={after_status!r}. "
                "Verify in Replicon UI if needed."
            )

        logger.info(
            "submit_timesheet_complete",
            extra={
                "timesheet_uri": resolved_uri,
                "before_status": before_status,
                "after_status": after_status,
            },
        )

        return TimesheetSubmitResponse(
            status="submitted",
            message="Weekly timesheet submitted for approval via Submit2.",
            user_uri=user_uri,
            timesheet_uri=resolved_uri,
            timesheet_display_text=identity.display_text,
            date=target_date,
            unit_of_work_id=unit_of_work_id,
            before_status=before_status,
            after_status=after_status,
            summary_before={"raw": summary_before},
            summary_after={"raw": summary_after},
            warnings=warnings,
            schema_notes=list(SUBMIT_SCHEMA_NOTES),
        )

    @staticmethod
    def build_submit2_payload(
        *,
        timesheet_uri: str,
        unit_of_work_id: str,
        comments: str | None = None,
        change_reason: str | None = None,
    ) -> dict[str, Any]:
        """Build na5 TimesheetApprovalService1/Submit2 request body."""
        payload: dict[str, Any] = {
            "timesheetUri": timesheet_uri,
            "unitOfWorkId": unit_of_work_id,
        }
        if comments is not None:
            payload["comments"] = comments
        if change_reason is not None:
            payload["changeReason"] = change_reason
        return payload

    @staticmethod
    def _extract_summary_status(summary_raw: dict[str, Any]) -> str | None:
        """Best-effort extraction of timesheet/approval status from summary."""
        data = summary_raw.get("d", summary_raw)
        if not isinstance(data, dict):
            return None
        for key in ("timesheetStatus", "approvalStatus"):
            value = data.get(key)
            if isinstance(value, str) and value.strip():
                return value.strip()
            if isinstance(value, dict):
                for nested_key in ("displayText", "name", "slug"):
                    nested = value.get(nested_key)
                    if isinstance(nested, str) and nested.strip():
                        return nested.strip()
                uri = value.get("uri")
                if isinstance(uri, str) and uri.strip():
                    return uri.strip()
        return None

    @staticmethod
    def _looks_already_submitted(status_text: str) -> bool:
        normalized = "".join(ch for ch in status_text.casefold() if ch.isalnum())
        return normalized in _ALREADY_SUBMITTED_STATUS_TOKENS

    def get_time_entry_revision_groups_for_date(
        self,
        *,
        user_uri: str,
        entry_date: date,
    ) -> list[dict[str, Any]]:
        """Fetch revision groups for a single calendar date (duplicate checks)."""
        payload = {
            "user": {"uri": user_uri},
            "dateRange": {
                "startDate": RepliconDate.from_date(entry_date).model_dump(),
                "endDate": RepliconDate.from_date(entry_date).model_dump(),
            },
        }
        response = self._client.get_time_entry_revision_groups_for_user_and_date_range(
            payload
        )
        data = self._client.unwrap_d(
            response,
            operation="GetTimeEntryRevisionGroupsForUserAndDateRange",
        )
        if data is None:
            return []
        if not isinstance(data, list):
            raise RepliconInvalidResponseError(
                "GetTimeEntryRevisionGroupsForUserAndDateRange expected an array in 'd'",
                operation="GetTimeEntryRevisionGroupsForUserAndDateRange",
                response_body=response,
            )
        return [item for item in data if isinstance(item, dict)]

    def resolve_task_uri(self, tasks_raw: dict[str, Any], task_name: str) -> str:
        """Resolve a task display name to its URI from GetProjectTaskDetailsForTimesheet."""
        wanted = task_name.strip().casefold()
        available: list[tuple[str, str]] = []

        data = tasks_raw.get("d", tasks_raw)
        if not isinstance(data, dict):
            raise TimeEntryValidationError(
                "Unexpected GetProjectTaskDetailsForTimesheet response shape",
                details={"timesheet_tasks": tasks_raw},
            )

        tasks = data.get("tasks")
        if not isinstance(tasks, list):
            raise TimeEntryValidationError(
                "No tasks list returned for timesheet",
                details={"timesheet_tasks": tasks_raw},
            )

        for item in tasks:
            if not isinstance(item, dict):
                continue
            name = self._extract_task_name(item)
            uri = self._extract_task_uri(item)
            if name and uri:
                available.append((name, uri))
                if name.casefold() == wanted:
                    return uri

        raise TimeEntryValidationError(
            f"Task '{task_name}' was not found on the timesheet",
            details={
                "requested_task": task_name,
                "available_tasks": [
                    {"name": name, "uri": uri} for name, uri in available
                ],
            },
        )

    def find_existing_entry_for_task(
        self,
        groups: list[dict[str, Any]],
        *,
        entry_date: date,
        task_uri: str,
    ) -> dict[str, Any] | None:
        """Return the first revision group matching entry date + task URI."""
        for group in groups:
            group_date = self._parse_replicon_date(group.get("entryDate"))
            if group_date != entry_date:
                continue
            if self._extract_task_uri_from_metadata(group) == task_uri:
                return group
        return None

    @staticmethod
    def build_put_time_entry_revision_group_payload(
        *,
        user_uri: str,
        task_uri: str,
        entry_date: date,
        hours: float,
        unit_of_work_id: str,
        is_billable: bool = False,
        target_uri: str | None = None,
    ) -> dict[str, Any]:
        """Build PutTimeEntryRevisionGroup body from verified OpenAPI + tenant example.

        Creates use target=null. Overwrites use target={uri: existing revision group}.
        """
        duration = TimesheetService._hours_to_calendar_duration(hours)
        target: Any = {"uri": target_uri} if target_uri else None
        return {
            "timeEntryRevisionGroup": {
                "target": target,
                "user": {"uri": user_uri},
                "interval": {
                    "hours": duration,
                    "timePair": None,
                },
                "timeAllocationTypeUris": [
                    TIME_ALLOCATION_TYPE_ATTENDANCE,
                    TIME_ALLOCATION_TYPE_PROJECT,
                ],
                "entryDate": RepliconDate.from_date(entry_date).model_dump(),
                "customMetadata": [
                    {
                        "keyUri": METADATA_KEY_IS_BILLABLE,
                        "value": {"bool": is_billable},
                    },
                    {
                        "keyUri": METADATA_KEY_TASK,
                        "value": {"uri": task_uri},
                    },
                ],
                "extensionFieldValues": [],
            },
            "unitOfWorkId": unit_of_work_id,
        }

    def update_timesheet(self, *_args: Any, **_kwargs: Any) -> None:
        """Bulk timesheet overwrite remains disabled.

        Use ``create_time_entry`` / ``POST /timesheets/time-entry`` for single
        PutTimeEntryRevisionGroup writes. PutStandardTimesheet2 is not used.
        """
        raise NotImplementedError(
            "Bulk timesheet update is disabled. Use create_time_entry "
            "(PutTimeEntryRevisionGroup) for single entries. "
            "PutStandardTimesheet2 is not used by this project."
        )

    def _validate_timesheet_for_write(
        self,
        *,
        user_uri: str,
        timesheet_uri: str | None,
        entry_date: date,
        warnings: list[str],
    ) -> str:
        """Resolve timesheet for user/date; optionally verify provided URI/period.

        Returns:
            The resolved timesheet URI to use for subsequent calls.
        """
        get_data = self.get_timesheet(user_uri, entry_date)
        identity = self.extract_timesheet_identity(get_data)
        resolved_uri = identity.uri

        if timesheet_uri and timesheet_uri != resolved_uri:
            raise TimeEntryValidationError(
                "timesheet_uri does not match the timesheet resolved for user/date",
                details={
                    "provided_timesheet_uri": timesheet_uri,
                    "resolved_timesheet_uri": resolved_uri,
                    "user_uri": user_uri,
                    "date": entry_date.isoformat(),
                },
            )

        details_raw = self.get_details(resolved_uri)
        timesheet_range = self._extract_timesheet_date_range(details_raw)
        if timesheet_range:
            start, end = timesheet_range
            if not (start <= entry_date <= end):
                raise TimeEntryValidationError(
                    "entry date is outside the timesheet period",
                    details={
                        "entry_date": entry_date.isoformat(),
                        "timesheet_start": start.isoformat(),
                        "timesheet_end": end.isoformat(),
                    },
                )
        else:
            # TODO: tighten once BulkGetTimesheetDetails dateRange shape is stable
            # across all tenant responses.
            warnings.append(
                "Could not extract timesheet dateRange from BulkGetTimesheetDetails; "
                "period membership was not fully verified."
            )

        # TODO: verify timesheet is not locked / approved before write when a
        # reliable status field is confirmed from BulkGetTimesheetDetails.
        # TODO: verify the caller has edit permission before write.

        return resolved_uri

    @staticmethod
    def _generate_unit_of_work_id() -> str:
        """Client-generated unique unitOfWorkId (OpenAPI: idempotent operations)."""
        return f"replicon-automation-{uuid.uuid4()}"

    @staticmethod
    def _hours_to_calendar_duration(hours: float) -> dict[str, int]:
        """Convert decimal hours to Replicon CalendarDayDuration1 hours/minutes/seconds."""
        total_seconds = int(round(hours * 3600))
        if total_seconds <= 0:
            raise TimeEntryValidationError("hours must be greater than 0")
        h = total_seconds // 3600
        rem = total_seconds % 3600
        m = rem // 60
        s = rem % 60
        return {"hours": h, "minutes": m, "seconds": s}

    @staticmethod
    def _extract_task_uri(item: dict[str, Any]) -> str | None:
        task_wrapper = item.get("task")
        if not isinstance(task_wrapper, dict):
            return None
        nested = task_wrapper.get("task")
        if isinstance(nested, dict):
            uri = nested.get("uri")
            if isinstance(uri, str) and uri.strip():
                return uri.strip()
        uri = task_wrapper.get("uri")
        if isinstance(uri, str) and uri.strip():
            return uri.strip()
        return None

    @staticmethod
    def _extract_task_uri_from_metadata(group: dict[str, Any]) -> str | None:
        metadata = group.get("customMetadata")
        if not isinstance(metadata, list):
            return None
        for item in metadata:
            if not isinstance(item, dict):
                continue
            if item.get("keyUri") != METADATA_KEY_TASK:
                continue
            value = item.get("value")
            if isinstance(value, dict):
                uri = value.get("uri")
                if isinstance(uri, str) and uri.strip():
                    return uri.strip()
        return None

    def _build_warnings(
        self,
        *,
        identity: TimesheetIdentity,
        details_raw: dict[str, Any],
        tasks_raw: dict[str, Any],
        target_date: date,
    ) -> list[str]:
        """Collect non-blocking warnings for the inspect response."""
        warnings: list[str] = []

        timesheet_range = self._extract_timesheet_date_range(details_raw)
        task_ranges = self._extract_task_allocation_ranges(tasks_raw)

        if timesheet_range and task_ranges:
            ts_start, ts_end = timesheet_range
            for task_name, (task_start, task_end) in task_ranges:
                if task_start != ts_start or task_end != ts_end:
                    warnings.append(
                        "Task allocation availability range does not match "
                        f"timesheet period for task '{task_name}': "
                        f"task={task_start.isoformat()}..{task_end.isoformat()}, "
                        f"timesheet={ts_start.isoformat()}..{ts_end.isoformat()}."
                    )

        if timesheet_range:
            ts_start, ts_end = timesheet_range
            if not (ts_start <= target_date <= ts_end):
                warnings.append(
                    f"Requested date {target_date.isoformat()} is outside the "
                    f"timesheet period {ts_start.isoformat()}..{ts_end.isoformat()} "
                    f"for {identity.display_text or identity.uri}."
                )

        return warnings

    def _extract_timesheet_date_range(
        self,
        details_raw: dict[str, Any],
    ) -> tuple[date, date] | None:
        """Best-effort extraction of dateRange from BulkGetTimesheetDetails."""
        try:
            data = details_raw.get("d", details_raw)
            if isinstance(data, list) and data:
                first = data[0]
            elif isinstance(data, dict):
                if "dateRange" in data:
                    first = data
                else:
                    for key in ("timesheetDetails", "results", "values"):
                        maybe = data.get(key)
                        if isinstance(maybe, list) and maybe:
                            first = maybe[0]
                            break
                    else:
                        first = data
            else:
                return None

            if not isinstance(first, dict):
                return None

            date_range = first.get("dateRange")
            if not isinstance(date_range, dict):
                return None

            start = self._parse_replicon_date(
                date_range.get("startDate") or date_range.get("start")
            )
            end = self._parse_replicon_date(
                date_range.get("endDate") or date_range.get("end")
            )
            if start and end:
                return start, end
        except (TypeError, ValueError, AttributeError):
            logger.debug("Could not extract timesheet date range from details", exc_info=True)
        return None

    def _extract_task_allocation_ranges(
        self,
        tasks_raw: dict[str, Any],
    ) -> list[tuple[str, tuple[date, date]]]:
        """Extract task allocation availability ranges from task details."""
        results: list[tuple[str, tuple[date, date]]] = []
        try:
            data = tasks_raw.get("d", tasks_raw)
            if not isinstance(data, dict):
                return results
            tasks = data.get("tasks")
            if not isinstance(tasks, list):
                return results

            for item in tasks:
                if not isinstance(item, dict):
                    continue
                name = self._extract_task_name(item) or "unknown"
                alloc = item.get("dateRangeWhereTimeAllocationIsAllowed")
                if not isinstance(alloc, dict):
                    continue
                start = self._parse_replicon_date(alloc.get("startDate"))
                end = self._parse_replicon_date(alloc.get("endDate"))
                if start and end:
                    results.append((name, (start, end)))
        except (TypeError, ValueError, AttributeError):
            logger.debug("Could not extract task allocation ranges", exc_info=True)
        return results

    @staticmethod
    def _extract_task_name(item: dict[str, Any]) -> str | None:
        task_wrapper = item.get("task")
        if not isinstance(task_wrapper, dict):
            return None
        nested = task_wrapper.get("task")
        if isinstance(nested, dict):
            for key in ("displayText", "name"):
                value = nested.get(key)
                if isinstance(value, str) and value.strip():
                    return value.strip()
        for key in ("displayText", "name"):
            value = task_wrapper.get(key)
            if isinstance(value, str) and value.strip():
                return value.strip()
        return None

    @staticmethod
    def _parse_replicon_date(value: Any) -> date | None:
        if not isinstance(value, dict):
            return None
        try:
            year = int(value["year"])
            month = int(value["month"])
            day = int(value["day"])
            return date(year, month, day)
        except (KeyError, TypeError, ValueError):
            return None
